"""
Seed the site map and the section switches.

Every value comes from apps/content/seed.py, which was generated by reading
the templates — so a fresh database renders the site exactly as it rendered
before Phase 2. The parity test is what proves it.

Re-running is safe: rows are matched on their natural key and updated, never
duplicated, and a section someone has hidden stays hidden.
"""

from django.db import migrations

from apps.content.seed import PAGES_SEED


def seed(apps, schema_editor):
    Page = apps.get_model("content", "Page")
    Section = apps.get_model("content", "Section")

    for order, row in enumerate(PAGES_SEED, start=1):
        page, _ = Page.objects.update_or_create(
            name=row["name"],
            defaults={
                "label": label_for(row["name"]),
                "title": row["title"],
                "meta_description": row["meta_description"],
                "og_image": row["og_image"],
                "status": row["status"],
                "sort_order": order,
            },
        )
        for position, (key, label, blurb) in enumerate(row["sections"], start=1):
            Section.objects.update_or_create(
                page=page, key=key,
                defaults={"label": label, "blurb": blurb, "sort_order": position},
            )


def unseed(apps, schema_editor):
    Page = apps.get_model("content", "Page")
    Page.objects.filter(name__in=[row["name"] for row in PAGES_SEED]).delete()


def label_for(name: str) -> str:
    """A readable name for the console's page list."""
    return OVERRIDES.get(name) or name.replace("_", " ").capitalize()


